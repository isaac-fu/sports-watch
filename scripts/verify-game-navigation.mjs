// Run against a local dev server with Playwright installed. All API responses are fixtures.
import { createRequire } from "node:module";
import assert from "node:assert/strict";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(15_000);
  await page.clock.install();
  const errors = [];
  const monthRequests = new Map();
  let releaseHome;
  const homeGate = new Promise((resolve) => { releaseHome = resolve; });
  let holdMonth = false;
  let releaseMonth;
  const monthGate = new Promise((resolve) => { releaseMonth = resolve; });
  page.on("pageerror", (error) => errors.push(error.message));
  const teams = [{ id: "gsw", name: "Golden State Warriors", short: "GSW", color: "#4488ff", record: "1-0" }, { id: "lal", name: "Los Angeles Lakers", short: "LAL", color: "#ffaa22", record: "0-1" }];
  const player = { id: "stephen-curry", name: "Stephen Curry", teamId: "gsw", teamName: teams[0].name, initials: "SC", color: "#4488ff", position: "Guard" };
  teams[0].record = "73–9"; // Deliberately stale catalog record; My Teams must not display it.
  const dateKey = (date) => `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
  const now = new Date();
  const oldDate = dateKey(new Date(now.getFullYear(), now.getMonth() - 1, 15));
  const futureDate = dateKey(new Date(now.getFullYear(), now.getMonth(), now.getDate() + 1));
  const final = { id: "bdl-42", date: oldDate, time: "7:00 PM", status: "final", homeScore: 114, awayScore: 108, home: teams[0], away: teams[1], network: "NBA", venue: "Chase Center" };
  const future = { ...final, id: "bdl-43", date: futureDate, status: "scheduled" };
  const live = { ...final, id: "bdl-50", date: dateKey(now), status: "live", period: 3, clock: "5:21", homeScore: 80, awayScore: 78 };
  const otherLive = { ...live, id: "bdl-51", home: { ...teams[0], id: "bos", name: "Boston Celtics" }, away: { ...teams[1], id: "nyk", name: "New York Knicks" } };
  let gamesFinished = false;
  let homeRequests = 0;
  let allowHomeRecovery = false;
  let feedbackInterest = null;
  const newsMoment = { id: "news-test", title: "NBA betting preview", detail: "A league betting preview.", reason: "Recent NBA news", importanceScore: 70, source: "news" };
  const playerSeason = { playerId: player.id, playerName: player.name, teamId: "gsw", teamName: teams[0].name, season: 2026, seasonLabel: "2026-27", gamesPlayed: 3, pointsPerGame: 30, reboundsPerGame: 4, assistsPerGame: 8, stealsPerGame: 2, blocksPerGame: 1, turnoversPerGame: 3, fieldGoalPercentage: 50, threePointPercentage: 40, freeThrowPercentage: 90 };
  const line = { playerId: player.id, name: player.name, minutes: "32:10", points: 30, rebounds: 4, assists: 8, steals: 2, blocks: 0, turnovers: 3, fouls: 2, fieldGoals: "10-20", threePointers: "6-12", freeThrows: "4-5", freeThrowsMade: 4, plusMinus: 6 };
  await page.route("**/api/**", async (route) => {
    const url = new URL(route.request().url());
    const path = url.pathname;
    if (path === "/api/games" && !url.searchParams.has("from")) {
      await homeGate;
      homeRequests++;
      if (!allowHomeRecovery) {
        await route.fulfill({ json: { data: [], meta: { unavailable: true, rateLimited: true, retryAt: await page.evaluate(() => Date.now() + 60_000) } } });
        return;
      }
    }
    if (path === "/api/games" && url.searchParams.has("from") && holdMonth) {
      holdMonth = false;
      await monthGate;
    }
    if (path === "/api/games" && url.searchParams.has("from")) monthRequests.set(url.search, (monthRequests.get(url.search) ?? 0) + 1);
    let data = [];
    let meta = {};
    if (path === "/api/account") { data = { id: "test", displayName: "Test Fan", timezone: "America/Los_Angeles", email: "test@example.test", emailVerified: true }; meta = { authenticated: true, onboardingCompleted: true }; }
    else if (path === "/api/preferences") data = { followedTeamIds: ["gsw"], followedPlayerIds: [], alerts: {} };
    else if (path === "/api/catalog") data = { teams, players: [player] };
    else if (path === "/api/teams/records") { data = { gsw: "2–1", lal: "0–0" }; meta = { season: now.getMonth() >= 9 ? now.getFullYear() : now.getFullYear() - 1, stale: false, unavailable: false }; }
    else if (path === "/api/recommendations/discovery") data = { teams: [], players: [], games: [] };
    else if (path === "/api/games") data = url.searchParams.has("from") ? [final, future].filter((game) => game.date >= url.searchParams.get("from") && game.date <= url.searchParams.get("to")) : [future, ...[live, otherLive].map((game) => ({ ...game, status: gamesFinished ? "final" : "live" })), ...[44, 45, 46].map((id) => ({ ...future, id: `bdl-${id}`, home: { ...teams[0], id: `unfollowed-${id}` }, away: { ...teams[1], id: `other-${id}` } }))];
    else if (path.startsWith("/api/games/")) {
      const game = path.includes("bdl-42") ? final : future;
      data = path.endsWith("/box-score") ? { gameId: game.id, source: "nba_api", status: game.status === "scheduled" ? "pending" : "available", updatedAt: new Date().toISOString(), teams: [{ teamId: "gsw", name: teams[0].name, players: [line], totals: line }] } : { game, events: [], keyMoments: [], source: "balldontlie", playByPlayStatus: "unavailable", updatedAt: new Date().toISOString() };
    } else if (path.startsWith("/api/teams/")) data = { team: teams[0], roster: [player], seasonLabel: "2026-27", stats: { wins: 1, losses: 0, conferenceRank: 1, pointsPerGame: 114, pointsAllowedPerGame: 108 }, rankings: { record: 1, conference: 1, pointsPerGame: 1, pointsAllowedPerGame: 1, pointDifferential: 1, leagueSize: 30 }, standings: [], standingsSeasonLabel: "2026-27", standingsUsesPreviousSeason: false, recentGames: [final], upcomingGames: [future], articles: [], source: "nba_api", updatedAt: new Date().toISOString() };
    else if (path.startsWith("/api/players/")) data = { player, bio: {}, currentSeason: playerSeason, career: null, seasons: [playerSeason], lastTenGames: [{ ...line, id: "log", date: oldDate, opponentShort: "LAL", homeAway: "home", result: "W", score: "114-108" }], source: "nba_api", updatedAt: new Date().toISOString() };
    else if (path === "/api/leaderboard") data = { players: [playerSeason, { ...playerSeason, playerId: "other", playerName: "Other Player", pointsPerGame: 20, reboundsPerGame: 12 }], teams: [{ teamId: "gsw", teamName: teams[0].name, wins: 2, losses: 1 }], seasonLabel: "2026-27", source: "nba_api", updatedAt: new Date().toISOString(), stale: false };
    else if (path === "/api/catch-up") { data = { title: "NBA catch-up", lede: "Recent NBA updates", readTimeMinutes: 1, generatedAt: String(Date.now()), game: null, moments: feedbackInterest === "not-interested" ? [] : [newsMoment], source: "news" }; meta = { ready: true }; }
    else if (path === "/api/news/news-test/feedback") { feedbackInterest = route.request().postDataJSON().interest; data = {}; }
    await route.fulfill({ json: { data, meta } });
  });
  await page.goto(process.env.TEST_BASE_URL || "http://localhost:3100", { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.getByText("Loading upcoming games…", { exact: true }).waitFor();
  assert.equal(await page.getByText("There are no upcoming games available.", { exact: true }).count(), 0);
  releaseHome();
  await page.getByText("The sports provider is rate-limiting requests. Retrying automatically after a cooldown.", { exact: true }).first().waitFor();
  const requestsBeforeCooldown = homeRequests;
  await page.clock.fastForward(31_000);
  assert.equal(homeRequests, requestsBeforeCooldown, "no retries during provider cooldown");
  allowHomeRecovery = true;
  await page.clock.fastForward(31_000);
  await page.locator(".upcoming-game").nth(3).waitFor();
  assert.equal(await page.getByText("The sports provider is rate-limiting requests. Retrying automatically after a cooldown.", { exact: true }).count(), 0, "successful retry clears errors without a reload");
  console.log("Rate-limit cooldown and automatic upcoming-game recovery passed");
  await page.locator(".home-live-games .game-card").nth(1).waitFor();
  assert.equal(await page.locator(".home-live-games .game-card").count(), 2, "Home shows every live matchup");
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Live games/ }).click();
  await page.locator(".live-games-grid .game-card").nth(1).waitFor();
  await page.getByRole("group", { name: "Filter live games" }).getByRole("button", { name: /Following/ }).click();
  assert.equal(await page.locator(".live-games-grid .game-card").count(), 1, "Following limits live games to followed teams");
  await page.getByRole("group", { name: "Filter live games" }).getByRole("button", { name: "All games", exact: true }).click();
  gamesFinished = true;
  await page.clock.fastForward(31_000);
  await page.getByText("No games are live right now.", { exact: true }).waitFor();
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Home/ }).click();
  await page.getByText("There are no live games right now.", { exact: true }).waitFor();
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Live games/ }).click();
  await page.getByText("No games are live right now.", { exact: true }).waitFor();
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Home/ }).click();
  console.log("All live games on Home, following filter, and live-to-final updates passed");
  await page.locator(".upcoming-game").nth(3).waitFor();
  assert.equal(await page.locator(".upcoming-game").count(), 4, "show all daily matchups including unfollowed teams");
  await page.getByRole("button", { name: "Open Los Angeles Lakers at Golden State Warriors game", exact: true }).first().click();
  await page.getByText("Box scores will be available after tip-off.").waitFor();
  await page.getByRole("button", { name: "← Home", exact: true }).click();
  console.log("Home game navigation passed");
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Schedule/ }).click();
  await page.locator(".schedule-layout[aria-busy=false]").waitFor();
  holdMonth = true;
  await page.getByRole("button", { name: "Previous month", exact: true }).click();
  await page.locator(".schedule-layout[aria-busy=true]").waitFor();
  await page.getByText("Loading games…", { exact: true }).first().waitFor();
  assert.equal(await page.getByText("No games available", { exact: true }).count(), 0, "never show empty state during fetch");
  releaseMonth();
  await page.getByRole("button", { name: "Open Los Angeles Lakers at Golden State Warriors box score", exact: true }).first().click();
  await page.getByRole("heading", { name: "LAL at GSW", level: 1, exact: true }).waitFor();
  await page.getByRole("cell", { name: "30", exact: true }).first().waitFor();
  const headers = await page.locator(".box-score-team table").first().locator("thead th").allTextContents();
  const ftColumn = headers.indexOf("FT");
  assert.equal(ftColumn, headers.indexOf("3PT") + 1, "FT immediately follows 3PT");
  assert.equal(await page.locator(".box-score-team tbody tr").first().locator("th,td").nth(ftColumn).textContent(), "4");
  assert.equal(await page.locator(".box-score-team tfoot tr").first().locator("th,td").nth(ftColumn).textContent(), "4");
  await page.getByRole("button", { name: "← Schedule", exact: true }).click();
  console.log("Historical game and box score passed");
  await page.getByRole("button", { name: "Open Los Angeles Lakers at Golden State Warriors box score", exact: true }).first().waitFor();
  const historicalKey = [...monthRequests.keys()].find((key) => new URLSearchParams(key).get("from") <= oldDate && new URLSearchParams(key).get("to") >= oldDate);
  assert.ok(historicalKey, "historical month was requested");
  await page.getByRole("button", { name: "Next month", exact: true }).click();
  await page.getByRole("button", { name: "Previous month", exact: true }).click();
  await page.getByRole("button", { name: "Open Los Angeles Lakers at Golden State Warriors box score", exact: true }).first().waitFor();
  assert.equal(monthRequests.get(historicalKey), 1, "returning to a cached month must not fetch it again");
  console.log("Schedule month cache reuse passed");
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /My teams/ }).click();
  await page.locator(".team-row-profile").getByText("2–1 record", { exact: true }).waitFor();
  assert.equal(await page.locator(".team-row-profile").getByText("73–9 record", { exact: true }).count(), 0);
  await page.locator(".team-row-profile").first().click();
  await page.locator(".team-roster-list").getByRole("button", { name: /Stephen Curry/ }).click();
  await page.getByRole("heading", { name: "Stephen Curry", exact: true }).waitFor();
  await page.getByRole("button", { name: "← Team profile", exact: true }).click();
  await page.getByRole("heading", { name: "Roster", exact: true }).waitFor();
  console.log("Roster and player return navigation passed");
  await page.locator(".team-roster-list").getByRole("button", { name: /Stephen Curry/ }).click();
  await page.getByRole("heading", { name: "Stephen Curry", exact: true }).waitFor();
  const recentTable = page.locator(".player-data-panel").filter({ has: page.getByRole("heading", { name: "Last 10 games", exact: true }) });
  assert.ok((await recentTable.locator("thead th").allTextContents()).includes("FT"));
  await recentTable.getByRole("cell", { name: "4-5", exact: true }).waitFor();
  const seasonTable = page.locator(".season-history");
  assert.equal((await seasonTable.locator("thead th").allTextContents()).at(-1), "FT%");
  await seasonTable.getByRole("cell", { name: "90", exact: true }).waitFor();
  await page.getByRole("button", { name: "View RPG leaderboard", exact: true }).click();
  await page.getByRole("heading", { name: "Player leaderboard · RPG", exact: true }).waitFor();
  const playerBoard = page.getByLabel("Player statistics leaderboard", { exact: true });
  assert.equal(await playerBoard.locator("tbody tr").first().getByRole("button").textContent(), "Other Player");
  assert.equal(await playerBoard.locator(".selected-player").getByRole("button").textContent(), "Stephen Curry");
  assert.deepEqual((await playerBoard.locator("thead th").allTextContents()).map((value) => value.replace(" ↓", "")), ["Rank", "Player", "PPG", "RPG", "APG", "SPG", "BPG", "FG%", "3P%", "FT%"]);
  await page.getByRole("button", { name: "Sort by FT%", exact: true }).click();
  await page.getByRole("heading", { name: "Player leaderboard · FT%", exact: true }).waitFor();
  await playerBoard.getByRole("button", { name: "Stephen Curry", exact: true }).click();
  await page.getByRole("button", { name: "← Leaderboard", exact: true }).click();
  await page.getByRole("heading", { name: "Leaderboard", exact: true }).waitFor();
  console.log("Leaderboard stat links, sorting, player return navigation, FT and FT% passed");
  await page.locator(".sidebar-bottom").getByRole("button", { name: /Settings/ }).click();
  await page.getByRole("button", { name: /Appearance Light and dark/ }).click();
  await page.getByRole("button", { name: "Violet", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.accentColor === "#9867eb");
  const darkCanvas = await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--canvas").trim());
  assert.equal(darkCanvas, await page.evaluate(() => document.documentElement.style.getPropertyValue("--sw-accent-canvas")));
  await page.getByRole("button", { name: /^Light Light surfaces/ }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  assert.notEqual(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue("--canvas").trim()), darkCanvas);
  assert.equal(await page.evaluate(() => localStorage.getItem("sports-watch-accent-color")), "#9867eb");
  await page.getByRole("button", { name: "Reset to brand blue", exact: true }).click();
  await page.waitForFunction(() => !document.documentElement.dataset.accentColor);
  await page.getByRole("navigation", { name: "Main navigation", exact: true }).getByRole("button", { name: /Home/ }).click();
  await page.locator(".catch-up-button").click();
  await page.getByRole("heading", { name: "NBA betting preview", exact: true }).waitFor();
  await page.getByLabel("News preferences", { exact: true }).click();
  await page.getByRole("button", { name: "Not interested", exact: true }).click();
  await page.getByText("There are no significant updates yet.", { exact: true }).waitFor();
  assert.equal(feedbackInterest, "not-interested");
  await page.getByRole("button", { name: "Close catch-up", exact: true }).click();
  console.log("Custom accent themes, reset, and catch-up feedback passed");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("navigation", { name: "Mobile navigation", exact: true }).getByRole("button", { name: /Leaderboard/ }).click();
  await page.getByRole("heading", { name: "Leaderboard", exact: true }).waitFor();
  await page.getByRole("heading", { name: /Player leaderboard/ }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile leaderboard scrolls within its table");
  await page.getByRole("navigation", { name: "Mobile navigation", exact: true }).getByRole("button", { name: /Schedule/ }).click();
  await page.getByRole("button", { name: "Open Los Angeles Lakers at Golden State Warriors box score", exact: true }).first().click();
  await page.getByRole("cell", { name: "30", exact: true }).first().waitFor();
  assert.equal(await page.getByRole("heading", { name: "Play-by-play", exact: true }).count(), 0);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile page must not overflow horizontally");
  assert.deepEqual(errors, [], "no client render errors");
  console.log("PASS: home matchup, historical calendar, box score, roster profile, return navigation, and mobile layout.");
} finally {
  await browser.close();
}
